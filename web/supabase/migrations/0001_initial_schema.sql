-- =====================================================================
-- Shryxa Ads — initial schema (fresh Supabase project)
--
-- Compatibility: the legacy Python app (auth/db.py) still runs against
-- this database during the migration, so the four original tables keep
-- its conventions: ISO-8601 TEXT timestamps and integer is_admin (0/1).
-- Meta tables use timestamptz because the Python code compares with NOW().
-- Tighten types at cutover (tracked in CLAUDE.md).
--
-- Security: RLS is enabled on every table with NO policies, so the
-- public anon/publishable key can read nothing. Both apps use privileged
-- credentials server-side (service role / postgres), which bypass RLS.
-- =====================================================================

begin;

-- ---------------------------------------------------------------- users
create table public.users (
  id             bigint generated by default as identity primary key,
  email          text not null unique,
  password_hash  text not null,
  currency       text not null default 'INR' check (currency in ('INR', 'USD')),
  tier           text not null default 'starter'
                 check (tier in ('starter', 'agency_lite', 'agency_standard', 'agency_pro')),
  client_limit   integer not null default 1 check (client_limit >= 0),
  team_seats     integer not null default 1 check (team_seats >= 0),
  is_admin       integer not null default 0 check (is_admin in (0, 1)),
  created_at     text not null,
  trial_ends_at  text not null
);

-- -------------------------------------------------------- subscriptions
create table public.subscriptions (
  user_id                   bigint primary key references public.users (id) on delete cascade,
  status                    text not null default 'trialing'
                            check (status in ('trialing', 'active', 'past_due', 'canceled', 'expired')),
  provider                  text,
  razorpay_subscription_id  text,
  razorpay_customer_id      text,
  current_period_end        text,
  paused_campaign_ids       text default '[]',
  last_polled_at            text
);

-- -------------------------------------------------------------- clients
create table public.clients (
  id                   bigint generated by default as identity primary key,
  user_id              bigint not null references public.users (id) on delete cascade,
  ad_account_id        text not null,
  page_id              text,
  business_name        text,
  created_at           text not null,
  service_model        text not null default 'self_service'
                       check (service_model in ('self_service', 'agency_managed')),
  billing_arrangement  text
                       check (billing_arrangement in ('management_fee_only', 'management_plus_ad_budget')),
  client_status        text not null default 'pending_access'
                       check (client_status in ('pending_access', 'active', 'paused')),
  unique (user_id, ad_account_id)
);
create index clients_user_id_idx on public.clients (user_id);

-- ------------------------------------------------------------- sessions
create table public.sessions (
  token       text primary key,
  user_id     bigint not null references public.users (id) on delete cascade,
  created_at  text not null,
  expires_at  text not null
);
create index sessions_user_id_idx on public.sessions (user_id);

-- ----------------------------------------------------- meta_connections
-- One Meta connection per client. Access token is Fernet-encrypted.
create table public.meta_connections (
  id                      bigint generated by default as identity primary key,
  user_id                 bigint not null references public.users (id) on delete cascade,
  client_id               bigint not null unique references public.clients (id) on delete cascade,
  meta_user_id            text,
  meta_user_name          text,
  ad_account_id           text not null,
  ad_account_name         text,
  access_token_encrypted  text not null,
  token_expires_at        timestamptz,
  connected_at            timestamptz not null default now(),
  updated_at              timestamptz not null default now(),
  connection_status       text not null default 'connected'
                          check (connection_status in ('connected', 'expired', 'revoked', 'error'))
);
create index meta_connections_user_id_idx on public.meta_connections (user_id);

-- ---------------------------------------------------- meta_oauth_states
-- One-time OAuth `state` values (stored hashed), short-lived.
create table public.meta_oauth_states (
  id          bigint generated by default as identity primary key,
  state_hash  text not null unique,
  user_id     bigint not null references public.users (id) on delete cascade,
  client_id   bigint not null references public.clients (id) on delete cascade,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null
);
create index meta_oauth_states_expires_idx on public.meta_oauth_states (expires_at);

-- --------------------------------------------------- meta_oauth_pending
-- Token + ad-account list held between OAuth callback and account pick.
create table public.meta_oauth_pending (
  id                      bigint generated by default as identity primary key,
  ticket_hash             text not null unique,
  user_id                 bigint not null references public.users (id) on delete cascade,
  client_id               bigint not null references public.clients (id) on delete cascade,
  meta_user_id            text,
  meta_user_name          text,
  accounts                jsonb not null,
  access_token_encrypted  text not null,
  token_expires_at        timestamptz,
  created_at              timestamptz not null default now(),
  expires_at              timestamptz not null
);
create index meta_oauth_pending_user_id_idx on public.meta_oauth_pending (user_id);

-- ------------------------------------------------------------------ RLS
alter table public.users              enable row level security;
alter table public.subscriptions      enable row level security;
alter table public.clients            enable row level security;
alter table public.sessions           enable row level security;
alter table public.meta_connections   enable row level security;
alter table public.meta_oauth_states  enable row level security;
alter table public.meta_oauth_pending enable row level security;

commit;
