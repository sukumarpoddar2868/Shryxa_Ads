-- =====================================================================
-- 0002 — Account types, client Meta assets, invite links (Phase 2)
--
-- Model:
--   users.account_type     'business' (one auto client "My business")
--                          | 'agency' (many clients)
--   meta_connections       one Meta login (encrypted token). Belongs to the
--                          workspace owner (user_id). client_id is now
--                          optional (legacy one-per-client still allowed).
--   clients                chosen assets: ad account, Page, Instagram,
--                          Pixel + which connection to use.
--   client_invites         magic link so a client can connect their own
--                          Facebook without a Shryxa account.
-- Additive / relaxing only: no data is rewritten or dropped.
-- =====================================================================

begin;

-- --------------------------------------------------------------- users
alter table public.users
  add column account_type text not null default 'agency'
    check (account_type in ('business', 'agency'));

-- ------------------------------------------------------------ clients
-- A client can exist before it is connected to Meta.
alter table public.clients alter column ad_account_id drop not null;

alter table public.clients
  add column is_self              boolean not null default false,
  add column meta_connection_id   bigint,
  add column ad_account_name      text,
  add column page_name            text,
  add column instagram_actor_id   text,
  add column instagram_username   text,
  add column pixel_id             text,
  add column pixel_name           text,
  add column assets_updated_at    timestamptz;

-- One "My business" client per business-type user.
create unique index clients_one_self_per_user
  on public.clients (user_id) where is_self;

-- ---------------------------------------------------- meta_connections
alter table public.meta_connections alter column client_id drop not null;
alter table public.meta_connections alter column ad_account_id drop not null;

alter table public.meta_connections
  add column source            text not null default 'owner'
    check (source in ('owner', 'invite', 'business')),
  add column token_type        text not null default 'user'
    check (token_type in ('user', 'system_user')),
  add column granted_scopes    text[],
  add column meta_business_id  text;

alter table public.clients
  add constraint clients_meta_connection_fk
  foreign key (meta_connection_id) references public.meta_connections (id) on delete set null;

-- ------------------------------------------------------ client_invites
create table public.client_invites (
  id          bigint generated by default as identity primary key,
  token_hash  text not null unique,
  user_id     bigint not null references public.users (id) on delete cascade,
  client_id   bigint not null references public.clients (id) on delete cascade,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null,
  used_at     timestamptz
);
create index client_invites_client_id_idx on public.client_invites (client_id);
alter table public.client_invites enable row level security;

-- --------------------------------------------------- meta_oauth_states
-- Which flow started the login, and (for invites) which invite.
alter table public.meta_oauth_states
  add column flow       text not null default 'owner'
    check (flow in ('owner', 'invite', 'business')),
  add column invite_id  bigint references public.client_invites (id) on delete cascade;

commit;
