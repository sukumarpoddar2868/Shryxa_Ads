-- 0004 · Campaigns created in Shryxa (text only — no media in the database).
-- One row per campaign: a saved draft (state = 'draft') or a launched one
-- (state = 'launched', with Meta ids). Live status/spend/results always come
-- from Meta; this table only remembers what Shryxa created and the draft.
-- Media files stay in Storage (bucket ad-media), never in this table.

create table public.campaigns (
  id                 bigint generated by default as identity primary key,
  user_id            bigint not null references public.users (id) on delete cascade,
  client_id          bigint not null references public.clients (id) on delete cascade,
  state              text   not null default 'draft' check (state in ('draft', 'launched')),
  name               text   not null default '',
  objective          text,                 -- OUTCOME_LEADS, OUTCOME_TRAFFIC, …
  destination        text,                 -- lead_form, whatsapp, website, …
  currency           text,                 -- INR / USD
  budget_type        text check (budget_type in ('daily', 'lifetime')),
  budget_minor       bigint,               -- paise / cents
  -- Meta ids once launched (null for drafts)
  meta_campaign_id   text unique,
  meta_adset_id      text,
  meta_ad_id         text,
  meta_form_id       text,
  -- Small text summary for the list (format, areas, audience type, headline…)
  summary            jsonb  not null default '{}'::jsonb,
  -- Full wizard draft as text/JSON (media = storage paths only, never file data)
  draft              jsonb,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  launched_at        timestamptz
);

create index campaigns_user_id_idx   on public.campaigns (user_id, updated_at desc);
create index campaigns_client_id_idx on public.campaigns (client_id, updated_at desc);

-- Keep drafts small: a draft is a few KB of text; cap at 200 KB as a safety net.
alter table public.campaigns
  add constraint campaigns_draft_size check (draft is null or pg_column_size(draft) < 200000);

alter table public.campaigns enable row level security; -- server-only access (service role), like other tables
